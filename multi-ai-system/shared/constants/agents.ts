// Get agent by ID
export function getAgentById(id: string): Agent | undefined {
  return AGENT_ROSTER.find(agent => agent.id === id);
}

// Get agent by name
export function getAgentByName(name: string): Agent | undefined {
  return AGENT_ROSTER.find(agent => agent.name === name);
}

// Get all active agents
export function getActiveAgents(): Agent[] {
  return AGENT_ROSTER.filter(agent => agent.isActive);
}

// Get agents by category
export function getAgentsByCategory(category: string): Agent[] {
  return AGENT_ROSTER.filter(agent => agent.category === category);
}

// Search agents by name or description
export function searchAgents(query: string): Agent[] {
  const lowerQuery = query.toLowerCase();
  return AGENT_ROSTER.filter(agent => 
    agent.name.toLowerCase().includes(lowerQuery) ||
    agent.description.toLowerCase().includes(lowerQuery) ||
    agent.capabilities.some(cap => cap.toLowerCase().includes(lowerQuery))
  );
}
